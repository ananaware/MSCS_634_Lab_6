from mlxtend.frequent_patterns import association_rules

min_confidence = 0.5     # a rule must be right at least 50% of the time

def make_rules(freq_itemsets):
    try:
        rules = association_rules(freq_itemsets, metric="confidence", min_threshold=min_confidence)
    except TypeError:
        # some mlxtend versions need the number of baskets
        rules = association_rules(freq_itemsets, num_itemsets=len(basket),
                                  metric="confidence", min_threshold=min_confidence)
    rules = rules[["antecedents", "consequents", "support", "confidence", "lift"]].copy()
    rules["antecedents"] = rules["antecedents"].apply(lambda s: ", ".join(sorted(s)))
    rules["consequents"] = rules["consequents"].apply(lambda s: ", ".join(sorted(s)))
    return rules

rules_apriori = make_rules(freq_apriori)
rules_fp = make_rules(freq_fp)

print("Minimum confidence:", min_confidence)
print("Rules from Apriori itemsets  :", len(rules_apriori))
